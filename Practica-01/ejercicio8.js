// Ejercicio 8: Descuento en una Compra
// Declare una variable con el precio original de un producto. Calcule un descuento del 20% y
// determine el precio final. Muestre el precio original, el descuento y el precio final.

let producto = 40;
let descuento = producto * 0.20;
let productoDescuento = producto - descuento;

console.log('Precio original: ' + producto);
console.log('Descuento: ' + descuento);
console.log('Precio final: ' + productoDescuento);